#!/usr/bin/env python3
"""Authenticate original metadata, then emit literal UAPI control fixtures."""
import hashlib
import json
import pathlib
import struct
import subprocess
import sys

repo = pathlib.Path(__file__).resolve().parents[2]
output = pathlib.Path(sys.argv[1])
rows = ["// Generated by tools/virgl-desktop-control/packets.py from authenticated original Mesa fields."]
for name in ["compositor", "kmscube", "glmark2-es2"]:
    root = repo / "evidence/virgl-corpus/captures" / name
    manifest = json.loads((root / "manifest.json").read_bytes())
    raw = (root / manifest["events"]["path"]).read_bytes()
    assert hashlib.sha256(raw).hexdigest() == manifest["events"]["sha256"]
    assert len(raw) == manifest["events"]["bytes"]
    rows.append(f"// {name} events SHA256 {manifest['events']['sha256']}")
    rows.append(f"pub const {name.upper().replace('-', '_')}: &[(u64, &[u8])] = &[")
    pending, bootstrap = {}, []
    for event in map(json.loads, raw.splitlines()):
        if event["type"] not in ["resource_create", "resource_unref"]:
            continue
        if event["phase"] == "enter":
            assert event["seq"] not in pending
            pending[event["seq"]] = event
            continue
        entered = pending.pop(event["callSeq"])
        assert event["result"] == 0 and entered["type"] == event["type"]
        if entered["resourceId"] == 2:
            bootstrap.append(entered)
            continue
        if entered["type"] == "resource_create":
            fields = [entered[k] for k in ["resourceId", "target", "format", "bind",
                       "width", "height", "depth", "arraySize", "lastLevel", "nrSamples", "flags"]]
            packet = struct.pack("<6I12I", 0x204, 0, 0, 0, 0, 0, *fields, 0)
        else:
            packet = struct.pack("<8I", 0x102, 0, 0, 0, 0, 0, entered["resourceId"], 0)
        rows.append(f"    ({entered['seq']}, &[" + ", ".join(map(str, packet)) + "]),")
    assert not pending and len(bootstrap) == 1
    assert bootstrap[0]["seq"] == 10 and bootstrap[0]["flags"] == 1
    rows.append("];")
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text("\n".join(rows) + "\n")
subprocess.run(["rustfmt", "--edition", "2024", str(output)], check=True)
