#!/usr/bin/env python3
"""Independently bind exact-head receipts, old refusals and declaration-only servers."""
import argparse
import hashlib
import json
import subprocess
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = 'b57c3ae04e0bd306e6bb5877ff94c5d8f4d6df06'
HEAD = 'b6434e33c9e5399f48fc191656e02f318cd78075'
sha = lambda raw: hashlib.sha256(raw).hexdigest()
def need(value, point):
    if not value:
        raise ValueError(point)
def git(head, path):
    return subprocess.check_output(['git', 'show', head + ':' + path], cwd=ROOT)


def main(root):
    reopened = root / 'worker-reopened'
    records, closure = [], {}
    for lane in ('hot', 'cold'):
        directory = reopened / lane
        receipt_file = directory / 'receipt.json'
        receipt = json.loads(receipt_file.read_text())
        need(receipt['status'] == 'passed' and receipt['gitHead'] == HEAD, lane + ' successful exact-head receipt')
        for path, digest in receipt['files'].items():
            need(sha((directory / path).read_bytes()) == digest, lane + ' receipt indexed full file ' + path)
        for path, digest in receipt['sources'].items():
            if path in receipt['carriedVerifiedEvidence']:
                need(sha((ROOT / path).read_bytes()) == receipt['carriedVerifiedEvidence'][path] == digest, lane + ' inherited closure seal member ' + path)
                closure[path] = digest
                continue
            if path.startswith('evidence/virgl-production-readiness/'):
                saved = (ROOT / path).read_bytes()
                need(saved == git(HEAD, path), lane + ' committed original gap/primary metadata ' + path)
            else:
                saved = (reopened / 'source' / path).read_bytes()
            need(sha(saved) == digest, lane + ' full recorded source closure ' + path)
            if path not in closure:
                need(saved == git(HEAD, path), lane + ' recorded source exactly committed head ' + path)
                closure[path] = digest
        for path, digest in receipt['generated'].items():
            need(sha((reopened / (lane + '-generated') / path).read_bytes()) == digest == sha((ROOT / path).read_bytes()), lane + ' exact actual generated bytes ' + path)
        for path, digest in receipt['carriedUnchangedBoundaries'].items():
            need(sha(git(BASE, path)) == digest == sha((ROOT / path).read_bytes()), lane + ' held old dependency boundary ' + path)
        for path, digest in receipt['carriedVerifiedEvidence'].items():
            need(sha((ROOT / path).read_bytes()) == digest, lane + ' independently authenticated carried seal ' + path)
        # Refusals are checked against observed records and analytic footprint accounting.
        wire_file = directory / 'wire/report.json'
        wire_envelope = json.loads(wire_file.read_text())
        wire = wire_envelope['wire']
        counts = audit_wire(wire)
        historical = []
        for name in ('integer-storage', 'float-storage', 'packed-float-storage', 'shared-storage', 'byte-storage', 'color-formats', 'resource-jobs'):
            p = directory / ('retained-' + name) / 'report.json'
            d = json.loads(p.read_text())
            need(d['status'] == 'passed' and d['gitHead'] == HEAD and d['browserResult']['status'] == 'passed', lane + ' live historical gate ' + name)
            need(d['browserErrors'] == dict(console=[], page=[], requests=[]) and not d['browser']['headless'], lane + ' historical browser errors/headed ' + name)
            encoded = json.dumps(d['browser']['gpu'])
            need('M4' in encoded and 'Metal' in encoded, lane + ' historical actual native GPU ' + name)
            for source in d['sources']:
                need(source['sha256'] == (closure.get(source['path']) or receipt['generated'].get(source['path'])), lane + ' historical same immutable source ' + source['path'])
            saved = d['browserResult']['result']
            assertions = saved.get('predictions', saved.get('assertions', []))
            need(all(item.get('held', item.get('passed', True)) for item in assertions), lane + ' historical assertions ' + name)
            historical.append(dict(path=p.relative_to(reopened).as_posix(), sha256=sha(p.read_bytes()), status='held'))
        records.append(dict(lane=lane, receiptSha256=sha(receipt_file.read_bytes()), files=len(receipt['files']), sourceFiles=len(receipt['sources']), wire=counts, historical=historical))
    cold_file = reopened / 'cold/report.json'
    cold = json.loads(cold_file.read_text())
    need(cold['gitHead'] == cold['cloneHead'] == HEAD and cold['status'] == 'passed' and cold['exitCode'] == 0 and cold['command'] == ['make', 'verify-E6-T11d35'], 'same pristine cold command')
    need(cold['statusBefore'] == cold['statusAfter'] == '', 'pristine cold before/after')
    need(cold['receiptSha256'] == sha((reopened / 'cold/receipt.json').read_bytes()) and cold['logSha256'] == sha((reopened / 'cold/cold.log').read_bytes()), 'pristine report/receipt/log binding')
    cold_source = (reopened / 'source/tools/virgl-command/standard-packed-normalized-cold.py').read_text()
    need("'RUST'" in cold_source and "'CARGO_'" in cold_source and "del env[key]" in cold_source, 'scrubbed Rust/Cargo environment algorithm source')
    # Every legacy server delta must be inside a single immutable declaration.
    boundary_path = ROOT / 'tools/virgl-command/standard-packed-normalized-serving-boundary.json'
    boundary = json.loads(boundary_path.read_text())
    servers = []
    for row in boundary['records']:
        text = (ROOT / row['path']).read_text()
        for edit in reversed(row['changes']):
            need(text.count(edit['after']) == 1, 'unique declared module edit ' + row['path'])
            need('packed-normalized-images' in edit['after'], 'declared packed module only ' + row['path'])
            text = text.replace(edit['after'], edit['before'], 1)
        original = git(BASE, row['path'])
        need(text.encode() == original and sha(original) == row['predecessorSha256'], 'no algorithm or assertion drift ' + row['path'])
        servers.append(dict(path=row['path'], sourceSha256=sha((ROOT / row['path']).read_bytes()), baseSha256=sha(original), declaredEdits=len(row['changes'])))
    need(len(servers) == 27, 'full 27 historical source lists')
    fresh_file = root / 'wire/report.json'
    fresh = audit_wire(json.loads(fresh_file.read_text())['wire'])
    gap_file = ROOT / 'evidence/virgl-production-readiness/standard-packed-normalized-image-gap.json'
    gap = json.loads(gap_file.read_text())
    need(gap['sourceSnapshotHead'] == BASE and gap['originalMetadataRecords'] == 78 and gap['allocations'] == 0, 'original D34 gap provenance/count')
    for source in gap['sources']:
        need(sha(git(BASE, source['path'])) == source['sha256'], 'original D34 refusal source ' + source['path'])
    replay_file = root / 'baseline-refusals.json'
    replay = json.loads(replay_file.read_text())
    need(replay['status'] == 'passed' and replay['allocations'] == 0 and len(replay['records']) == 78, 'independent D34 source replay')
    need(all(not row['create']['ok'] and not row['layout']['ok'] and row['allocations'] == 0 for row in replay['records']), 'original D34 preallocation refusals')
    result = dict(schema='d35-critic-exact-receipts-and-held-boundaries-v1', status='passed', records=records,
                  originalGap=dict(sha256=sha(gap_file.read_bytes()), replaySha256=sha(replay_file.read_bytes()), refused=78, allocations=0),
                  freshWire=dict(sha256=sha(fresh_file.read_bytes()), counts=fresh),
                  cold=dict(sha256=sha(cold_file.read_bytes()), **cold), servers=servers, declarationWaiver='Source-serving lists only; byte reversal proves no semantic changes.',
                  fullRecordedSourceClosure=closure)
    (root / 'receipt-values.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(dict(status='passed', exactHead=HEAD, sourceFiles=len(closure), receipts=2, legacyServers=len(servers), originalRefusals=78, freshWire=fresh)))


def audit_wire(wire):
    need(wire['status'] == 'passed' and all(p['held'] for p in wire['predictions']), 'all direct ownership assertions held')
    counts = Counter(row['kind'] for row in wire['records'])
    need(counts['old-owner'] == 780 and counts['old-layout'] == 702, 'full old profile refusal matrix')
    for row in wire['records']:
        kind, result = row['kind'], row['result']
        if kind in ('old-owner', 'old-layout'):
            need(not result['ok'] and result['error']['code'] == 'unsupported-resource', kind + ' remains closed')
        elif kind == 'layout':
            f, m, layout = row['fields'], row['metadata'], result['layout']
            size = 4 if m['format'] in (8, 131, 308) else 2
            box = f['box']
            rowbytes = box['width'] * size
            footprint = (box['height'] - 1) * f['stride'] + rowbytes
            need(result['ok'] and layout['rowBytes'] == rowbytes and layout['footprintBytes'] == footprint and layout['requiredEnd'] == f['dataOffset'] + footprint and layout['tightBytes'] == box['width'] * box['height'] * size, 'analytic original packed layout')
            need(layout['scratchBytes'] == box['width'] * box['height'] * (4 if f['direction'] == 2 else size) and layout['stagingBytes'] == (box['width'] * box['height'] * 4 if f['direction'] == 2 else 0), 'analytic packed scratch/PBO charge')
        elif kind == 'hostile-metadata':
            need(not result['ok'] and row['calls'] == 0, 'accessors/traps never evaluated')
        elif kind == 'allocation-bound':
            need(row['allocations'] == int(result['ok']), 'bound refusal before allocation')
            m = row['metadata']
            size = 4 if m['format'] in (8, 131, 308) else 2
            logical = sum(max(1, m['width'] >> level) * max(1, m['height'] >> level) * size for level in range(m['lastLevel'] + 1))
            need(result['ok'] == (next(iter(row['limits'].values())) >= logical), 'analytic full-mip allocation boundary')
        elif kind == 'transfer-bound':
            f, m = row['fields'], row['metadata']
            size = 4 if m['format'] in (8, 131, 308) else 2
            footprint = (f['box']['height'] - 1) * f['stride'] + f['box']['width'] * size
            need(result['ok'] == (row['backingBytes'] >= f['dataOffset'] + footprint and row['limits'].get('transferBytes', 4194304) >= footprint), 'analytic exact/short padded footprint')
        else:
            need(not result['ok'], 'invalid metadata/transfer/backend/config refuses')
    return dict(counts)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True)
    main(parser.parse_args().root)
