import { chromium } from "/Users/blamy/.codex/worktrees/ui-redesign/wasm-vm/web/node_modules/@playwright/test/index.mjs";
const [, , base, prefix, w = "390", h = "844"] = process.argv;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: +w, height: +h }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
const errs = [];
p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
p.on("pageerror", (e) => errs.push("pageerror " + e.message));
await p.goto(base + "/index.html?nosw");
await p.getByRole("button", { name: "Start Linux" }).tap();
await p.waitForFunction(() => window.wvmDemo?.isGuestReady?.(), null, { timeout: 180000 });
await p.waitForTimeout(800);
await p.locator("#term").tap();
await p.keyboard.type("printf 'ui-%s-%s\\n' ready 42\n");
await p.waitForFunction(() => document.querySelector("#term .xterm-rows")?.textContent.includes("ui-ready-42"), null, { timeout: 30000 });
console.log("term", JSON.stringify(await p.locator("#term").boundingBox()), "overflowX", await p.evaluate(() => document.documentElement.scrollWidth - innerWidth));
await p.screenshot({ path: prefix + "-shell.png" });
await p.getByRole("button", { name: "Tools and settings" }).tap();
await p.waitForTimeout(700);
await p.screenshot({ path: prefix + "-tools.png" });
await p.getByRole("dialog").getByRole("button", { name: /^Files/ }).tap();
await p.waitForTimeout(1500);
await p.screenshot({ path: prefix + "-files.png" });
const small = await p.evaluate(() => [...document.querySelectorAll(".wv-ui button, .wv-ui a, .wv-ui [role=radio]")].filter((e) => e.offsetParent).map((e) => { const r = e.getBoundingClientRect(); return [e.textContent.trim().slice(0, 20) || e.getAttribute("aria-label"), Math.round(r.width), Math.round(r.height)]; }).filter(([, w, h]) => h < 44 || w < 44));
console.log("small targets", JSON.stringify(small));
console.log("errors", JSON.stringify(errs));
await b.close();
