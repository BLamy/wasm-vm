#!/usr/bin/env node
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const verifier = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(verifier, "../../..");
const runDirectory = path.join(repo, "evidence/e5-t26f/single-process-quiet-001e8086");
const rawPath = path.join(runDirectory, "record/failure-post-restore-interaction-checks.json");
const generatedPath = path.join(repo, "target/e5-t26f/single-process-quiet-001e8086/probe.mjs");
const factoryPath = path.join(repo, "tools/verify/e5-t26f-single-process-quiet-probe.mjs");
const sha256 = bytes => createHash("sha256").update(bytes).digest("hex");
const readJson = async filename => JSON.parse(await readFile(filename, "utf8"));
const digest = async filename => sha256(await readFile(filename));

const expected = Object.freeze({
  head: "001e80864911863145f2127192bae5df8186e68b",
  raw: "0d56d45f82d6982a52368ca5dc63499d26ce07409712d460b0cb178ab60363bf",
  invocation: "acd121ea09d7e1fa60a94f9071e3c20d70b7e08bc64e41207e9f8637bd36f652",
  summary: "48ef035791d4d188c662c4980693b6155119240f7d78abe5da98369fbdba69fd",
  exit: "0cf195d64edfa93e108082da543b5fe976bc4709e8021c314b822c486255c3d7",
  runLog: "2ef2bc5ef680f28bc0041de8d5dd873ceae404933e90bdaa2dd7ee8acc3b2dbf",
  launcher: "f8dad67f176ed94fae3c46e3d896ace20c491ef26c8e06ef05730bb19aa0507f",
  factory: "dcf52ced1640baf7dc3fb7f73bcd5b8ae1253679ea51e09469b1bd4cf3268ec5",
  generated: "58b735d6a2225cd6614c192af898d7b4878ae1124f39d2244867274684b3fa73",
  factoryRecord: "d84f3a69ec8e772308a2e473cd2eb01143ad8f56a36d285b615193fc7ec4bf57",
  quietPng: "9538a1c58c531ed7315b2e68c9204149b50e9dc739c4b44642d8cf7f68238431",
  finalPng: "80c5b4057a6c89ec7bd33f41995c390e0577ae1d90bd376c0756db77f60cd478",
  elapsedMs: 4101.870000004768,
  capMs: 2000,
});

const files = {
  raw: rawPath,
  invocation: path.join(runDirectory, "invocation.json"),
  summary: path.join(runDirectory, "summary.json"),
  exit: path.join(runDirectory, "exit.json"),
  runLog: path.join(runDirectory, "run.log"),
  launcher: path.join(runDirectory, "run.mjs"),
  factory: factoryPath,
  generated: generatedPath,
  factoryRecord: path.join(repo, "target/e5-t26f/single-process-quiet-001e8086/factory.json"),
  quietPng: path.join(runDirectory, "record/quiet-prepared.png"),
  postPng: path.join(runDirectory, "record/post-restore.png"),
  failurePng: path.join(runDirectory, "record/failure-post-restore-interaction-checks.png"),
};
for (const key of ["raw", "invocation", "summary", "exit", "runLog", "launcher", "factory",
  "generated", "factoryRecord", "quietPng"]) assert.equal(await digest(files[key]), expected[key], key);
assert.equal(await digest(files.postPng), expected.finalPng);
assert.equal(await digest(files.failurePng), expected.finalPng);
assert.deepEqual(await readFile(files.postPng), await readFile(files.failurePng));

const invocation = await readJson(files.invocation);
const factoryRecord = await readJson(files.factoryRecord);
const summary = await readJson(files.summary);
const exit = await readJson(files.exit);
const raw = await readJson(files.raw);
const milestones = raw.milestones;
const run = milestones.run;
assert.equal(invocation.head, expected.head);
assert.equal(invocation.acceptance, false);
assert.equal(invocation.fVerified, false);
assert.deepEqual(invocation.factory, factoryRecord);
assert.equal(invocation.factory.factorySha256, expected.factory);
assert.equal(invocation.factory.generatedSourceSha256, expected.generated);
for (const [relative, hash] of Object.entries(invocation.sourceBindings)) {
  assert.equal(await digest(path.join(repo, relative)), hash, `source binding: ${relative}`);
}

// Re-derive without generating, launching or writing, then require the actual generated bytes.
const { SOURCE_PINS, deriveQuietProbe } = await import(pathToFileURL(factoryPath).href);
const sources = Object.fromEntries(await Promise.all(Object.keys(SOURCE_PINS).map(async relative =>
  [relative, await readFile(path.join(repo, relative))])));
const derived = deriveQuietProbe(sources);
assert.equal(sha256(derived.source), expected.generated);
assert.deepEqual(Buffer.from(derived.source), await readFile(generatedPath));
assert.equal(derived.changes.length, 17);

assert.deepEqual(exit, { code: 1, signal: null });
assert.equal(summary.rawSha256, expected.raw);
assert.equal(summary.childExit, 1);
assert.equal(summary.elapsedMs, expected.elapsedMs);
assert.equal(summary.originalCapMs, expected.capMs);
assert.equal(summary.printOnlyScreenPassed, false);
assert.equal(summary.acceptance, false);
assert.equal(summary.fVerified, false);
assert.equal(raw.head, expected.head);
assert.equal(raw.label, "failure-post-restore-interaction-checks");
assert.equal(raw.error?.message, "post-restore interaction exceeded 2 seconds");
assert.equal(raw.lastPhase?.phase, "post-restore:interaction-checks");
assert.equal(raw.lastPhase?.event, "failed");

// Actual fixture and generated-source provenance.
assert.equal(run.acceptance, false);
assert.equal(run.singleProcessQuiet.fVerified, false);
assert.equal(run.singleProcessQuiet.generatedSourceSha256, expected.generated);
assert.equal(run.binding.head, expected.head);
assert.equal(run.binding.runtimeSha256, run.singleProcessQuiet.seal.runtimeSha256);
assert.equal(run.binding.imageSha256, run.singleProcessQuiet.seal.imageSha256);
assert.equal(run.profileSha256, run.singleProcessQuiet.seal.profileSha256);
assert.deepEqual(run.binding.fixture, milestones.residentCheckpoint.fixture);
assert.equal(run.binding.fixture.helperSha256,
  invocation.sourceBindings["tools/guest/e5-t26f-resident-observer.sh"]);
assert.equal(run.binding.fixture.observer.sourceSha256,
  invocation.sourceBindings["tools/guest/e5-t26f-observer.c"]);
assert.equal(run.binding.fixture.observer.sha256,
  invocation.sourceBindings["target/e5-t26f/observer-build-v1/e5t26f-observe"]);

const helper = await readFile(path.join(repo, "tools/guest/e5-t26f-resident-observer.sh"), "utf8");
const observer = await readFile(path.join(repo, "tools/guest/e5-t26f-observer.c"), "utf8");
const generated = await readFile(generatedPath, "utf8");
for (const token of ['e5_observe && [ "$e5_seen" = "$e5_expected" ]', 'if wait "$e5_pid"; then',
  "e5_print_observation post"]) assert.ok(helper.includes(token), token);
for (const token of ["first.start != last.start", "child.fifo_count != 1", "child.pcm_count != 1",
  "!parse_pcm(&text, pid)"]) assert.ok(observer.includes(token), token);
assert.ok(generated.includes("e5_print_observation(){ :; }"));

// Closed 05b seed authentication and distinct derived RAM snapshot.
const seal = run.singleProcessQuiet.seal;
const baseline = milestones.quietProbe.baselineRestore;
assert.equal(baseline.snapshotSha256, seal.snapshotSha256);
assert.equal(baseline.observation.firstPresent.crc32, milestones.quietProbe.baselineSnapshot.preFrontBufferCrc);
assert.equal(baseline.coherenceAudit.status, "passed");
assert.equal(baseline.coherenceAudit.restoreBoundary.decision, "resume");
assert.ok(!baseline.bootStates.some(item => item.state === "booting"));
const snapshot = milestones.normalSnapshot;
const restored = milestones.normalRestore.result;
assert.notEqual(snapshot.sha256, seal.snapshotSha256);
assert.equal(milestones.normalCheckpointBeforeReload.status, "passed");
assert.equal(milestones.normalCheckpointBeforeReload.snapshotSha256, snapshot.sha256);
assert.equal(milestones.normalCheckpointBeforeReload.observed.envelopeSha256, snapshot.sha256);
assert.equal(restored.snapshotSha256, snapshot.sha256);
assert.equal(restored.observation.firstPresent.crc32, snapshot.preFrontBufferCrc);
assert.deepEqual(restored.machineResume, snapshot.machineResume);
assert.equal(restored.report.fullRepairFrame, true);
assert.equal(restored.report.agentRehandshake, true);
assert.equal(restored.resume.restored, true);
assert.ok(!restored.bootStates.some(item => item.state === "booting"));

// Fresh physical text/focus/raster and fresh audio, with stale/prequeued PCM excluded.
assert.equal(milestones.postRestoreStart, restored.completedAt);
assert.equal(milestones.postRestoreEnd - milestones.postRestoreStart, expected.elapsedMs);
assert.ok(expected.elapsedMs > expected.capMs);
assert.equal(milestones.postRestoreCursor.elapsedMs, 824.6200000047684);
assert.equal(milestones.quietText.baseline.focused, true);
assert.deepEqual(milestones.quietText.baseline.matches, []);
assert.equal(milestones.quietText.observed.focused, true);
assert.equal(milestones.quietText.observed.focus.accepted, true);
assert.equal(milestones.quietText.observed.redPixels, 0);
assert.deepEqual(milestones.quietText.observed.matches, [{ x: 557, y: 195 }]);
const expectedKeys = ["KeyP", "KeyL", "KeyA", "KeyY", "Enter"].flatMap(code =>
  [{ code, value: 1, type: "keydown" }, { code, value: 0, type: "keyup" }]);
assert.deepEqual(milestones.quietText.observed.frames.map(({ code, value }) => ({ code, value })),
  expectedKeys.map(({ code, value }) => ({ code, value })));
assert.deepEqual(milestones.quietText.observed.events.map(({ code, type }) => ({ code, type })),
  expectedKeys.map(({ code, type }) => ({ code, type })));
assert.equal(milestones.postRestoreAplay.oracle, "fresh-exact-reviewed-raster");
assert.deepEqual(milestones.postRestoreAplay.baselineMatches, []);
for (const sample of milestones.residentBeforeGesture) {
  assert.equal(sample.policy, "locked");
  assert.equal(sample.pcm.writtenFrames, 0);
  assert.equal(sample.pcm.nonSilentFrames, 0);
  assert.equal(sample.pcm.maxAbs, 0);
}
assert.equal(milestones.residentBeforeGesture.length, 2);
const pcm = milestones.postRestorePcmAtCompletion.pcm;
assert.equal(pcm.writtenFrames, 1440);
assert.equal(pcm.nonSilentFrames, 1440);
assert.ok(pcm.maxAbs > 0);
assert.equal(milestones.postRestoreAudioAfter.guestAttached, true);
assert.ok(milestones.postRestoreAudioAfter.renderedFrames > milestones.postRestoreAudioBefore.renderedFrames);
assert.deepEqual(milestones.postRestoreInteraction.heldButtons, []);

function pngSize(bytes) {
  assert.deepEqual([...bytes.subarray(0, 8)], [137, 80, 78, 71, 13, 10, 26, 10]);
  return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
}
assert.deepEqual(pngSize(await readFile(files.quietPng)), { width: 1440, height: 1145 });
assert.deepEqual(pngSize(await readFile(files.failurePng)), { width: 1440, height: 1145 });

console.log(JSON.stringify({
  schema: "wasm-vm.e5-t26f.single-process-quiet-verifier.v1",
  verdict: "closed-original-cap-failure",
  acceptance: false,
  fVerified: false,
  head: expected.head,
  rawSha256: expected.raw,
  generatedSourceSha256: expected.generated,
  elapsedMs: expected.elapsedMs,
  originalCapMs: expected.capMs,
  preparedIdentityFromVisualReview: { pid: 1000, start: 31468 },
  restoredSnapshotSha256: snapshot.sha256,
  restoredCrc32: snapshot.preFrontBufferCrc,
  freshRaster: { text: milestones.postRestoreAplay.text, match: { x: 557, y: 195 }, physicalEdges: 10 },
  freshPcm: { writtenFrames: pcm.writtenFrames, nonSilentFrames: pcm.nonSilentFrames, maxAbs: pcm.maxAbs },
  pngSha256: { quietPrepared: expected.quietPng, postRestoreAndFailure: expected.finalPng },
  limitation: "Closes only the one authorized print-suppression hypothesis; no F acceptance or speedup claim.",
}, null, 2));
